use crate::category::Category;
use crate::language::Language;
use crate::types::{Issue, Severity};

pub const NAME: &str = "long-line";

/// Seuil par langage (utilisé quand la config demande "auto", `max == 0`) —
/// même convention que les autres métriques (voir `metrics.rs`). PHP/C#/Java
/// dépassent régulièrement 120 sur des lignes légitimes : signatures avec
/// types nullables verbeux (PHP), tableaux d'initialisation typés (C#),
/// génériques imbriqués (Java) — 120 pour tous pénalisait structurellement
/// ces langages plus que Python/Rust/Go, alors que ce n'est pas un vrai
/// problème de lisibilité dans ces idiomes.
fn default_max_line_length(lang: Language) -> usize {
    match lang {
        Language::Php | Language::CSharp | Language::Java => 150,
        _ => 120,
    }
}

/// Marqueurs usuels d'un fichier généré automatiquement (docs auto-générées,
/// bindings protobuf/gRPC, migrations, code-gen…) — sur ces fichiers, une
/// ligne trop longue n'est pas quelque chose qu'un humain va corriger à la
/// main, il faudrait changer le générateur. Cherché dans les 60 premières
/// lignes plutôt que 20 (un gros docblock de licence peut repousser le
/// marqueur après la ligne 40, comme sur Carbon) — mais pas tout le fichier,
/// pour éviter qu'une phrase du corps ("// ne pas éditer sans...") supprime
/// à tort la vérification sur un fichier par ailleurs normal.
fn looks_generated(code: &str) -> bool {
    code.lines().take(60).any(|l| {
        let l = l.to_ascii_lowercase();
        l.contains("@generated")
            || l.contains("generated by")
            || l.contains("autodoc generated")
            || l.contains("auto-generated")
            || l.contains("do not edit")
    })
}

pub fn check(code: &str, lang: Option<Language>, max: usize) -> Vec<Issue> {
    let max = if max == 0 { lang.map(default_max_line_length).unwrap_or(120) } else { max };
    if max == 0 || looks_generated(code) {
        return Vec::new();
    }

    code.lines()
        .enumerate()
        .filter_map(|(i, line)| {
            let len = line.chars().count();
            // Skip lines whose length comes from an unsplittable URL.
            if len <= max || line.contains("http://") || line.contains("https://") {
                return None;
            }
            Some(Issue {
                rule: NAME.to_string(),
                category: Category::Quality,
                severity: Severity::Warning,
                message: format!("Ligne trop longue : {len} caractères (max {max}) — découpe-la pour la lisibilité"),
                line: i + 1,
                column: max + 1,
            })
        })
        .collect()
}
